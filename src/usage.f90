!----------------------------------------------------------------------
subroutine usage (u)
!
!-----Prints the INTRACULE input-file keyword documentation.
!     Argument:
!       u : logical unit number where the text is written.
!           If u <= 0, unit 6 (stdout) is used.
!
    implicit none
    integer, intent(in) :: u
    integer :: lu

    lu = u
    if (lu <= 0) lu = 6

    write (lu,'(a)') '================================================================================================================'
    write (lu,'(a)') '                    INTRACULE - INPUT FILE KEYWORDS'
    write (lu,'(a)') '================================================================================================================'
    write (lu,'(a)') ''
    write (lu,'(a)') 'The input file is passed to the program either by shell redirection:'
    write (lu,'(a)') ''
    write (lu,'(a)') '    intracule < input_file > output_file'
    write (lu,'(a)') ''
    write (lu,'(a)') 'or as a positional argument:'
    write (lu,'(a)') ''
    write (lu,'(a)') '    intracule input_file output_file'
    write (lu,'(a)') ''
    write (lu,'(a)') 'The format is classic Fortran: one keyword per line, optionally followed by its arguments separated by blanks.'
    write (lu,'(a)') 'Blank lines are ignored. Lines starting with ''#'' are ignored.'
    write (lu,'(a)') ''
    write (lu,'(a)') '----------------------------------------------------------------------------------------------------------------'
    write (lu,'(a)') '1. GENERAL STRUCTURE OF THE INPUT FILE'
    write (lu,'(a)') '----------------------------------------------------------------------------------------------------------------'
    write (lu,'(a)') ''
    write (lu,'(a)') '    <wfn_file_name>              <- FIRST line: WFN file'
    write (lu,'(a)') '    <keyword> [arguments]        <- following lines'
    write (lu,'(a)') '    <keyword> [arguments]'
    write (lu,'(a)') '    ...'
    write (lu,'(a)') ''
    write (lu,'(a)') 'The first non-blank line of the file is ALWAYS the name of the WFN file containing the wavefunction. All'
    write (lu,'(a)') 'subsequent lines are control keywords.'
    write (lu,'(a)') ''
    write (lu,'(a)') '----------------------------------------------------------------------------------------------------------------'
    write (lu,'(a)') '2. RECOGNIZED KEYWORDS'
    write (lu,'(a)') '----------------------------------------------------------------------------------------------------------------'
    write (lu,'(a)') ''
    write (lu,'(a)') 'INTRACULE'
    write (lu,'(a)') '    Usage:    INTRACULE'
    write (lu,'(a)') '    Type:     action (no arguments)'
    write (lu,'(a)') '    Effect:   Runs the intracule density calculation. This is the keyword that triggers the main'
    write (lu,'(a)') '              calculation. Without it, the program reads the WFN file but performs no calculation.'
    write (lu,'(a)') '    Example:  INTRACULE'
    write (lu,'(a)') ''
    write (lu,'(a)') 'END'
    write (lu,'(a)') '    Usage:    END'
    write (lu,'(a)') '    Type:     action (no arguments)'
    write (lu,'(a)') '    Effect:   This work MUST be used to indicate that no more input lines are to be read in.'
    write (lu,'(a)') '              Without it, the program ends correctly but a error message is printed.'
    write (lu,'(a)') '    Example:  END'
    write (lu,'(a)') ''
    write (lu,'(a)') 'THREADS <n>'
    write (lu,'(a)') '    Usage:    THREADS n'
    write (lu,'(a)') '    Type:     integer (n > 0)'
    write (lu,'(a)') '    Effect:   Sets the number of OpenMP threads to n. Only effective if the code was compiled'
    write (lu,'(a)') '              with OpenMP support (-fopenmp). Without OpenMP, the line is read but not applied.'
    write (lu,'(a)') '    Example:  THREADS 4'
    write (lu,'(a)') ''
    write (lu,'(a)') 'VERBOSE or BIGOUTPUT or LARGE'
    write (lu,'(a)') '    Usage:    VERBOSE or BIGOUTPUT or LARGE'
    write (lu,'(a)') '    Type:     flag (no arguments)'
    write (lu,'(a)') '    Effect:   Enables verbose output (verb=.true.). It also sets largwr=.true. during the first'
    write (lu,'(a)') '              pass over the input, so that the two-electron integration routines print extended information.'
    write (lu,'(a)') '    Example:  VERBOSE or BIGOUTPUT or LARGE'
    write (lu,'(a)') ''
    write (lu,'(a)') 'TEST'
    write (lu,'(a)') '    Usage:    TEST'
    write (lu,'(a)') '    Type:     flag (no arguments)'
    write (lu,'(a)') '    Effect:   Enables test mode (test=.true.). In this mode, INTRACULE calls newiculedrv instead'
    write (lu,'(a)') '              of otroiculedrv. Intended for validation and debugging.'
    write (lu,'(a)') '    Example:  TEST'
    write (lu,'(a)') ''
    write (lu,'(a)') '# comment'
    write (lu,'(a)') '    Usage:    # any text'
    write (lu,'(a)') '    Type:     comment'
    write (lu,'(a)') '    Effect:   The line is ignored. Any line whose first non-blank character is ''#'' is'
    write (lu,'(a)') '              treated as a comment.'
    write (lu,'(a)') '    Example:  # this line does nothing'
    write (lu,'(a)') ''
    write (lu,'(a)') '----------------------------------------------------------------------------------------------------------------'
    write (lu,'(a)') '3. ORDER AND COMBINATIONS'
    write (lu,'(a)') '----------------------------------------------------------------------------------------------------------------'
    write (lu,'(a)') ''
    write (lu,'(a)') '- The order of keywords is free, except that the FIRST non-blank line must be the WFN file name.'
    write (lu,'(a)') '- INTRACULE may appear one or more times; each occurrence triggers a calculation using the current'
    write (lu,'(a)') '  state of verb/test. VERBOSE, BIGOUTPUT and LARGE are cumulative: any one of them is enough to set largwr=.true. in the first pass.'
    write (lu,'(a)') '- TEST and VERBOSE are independent: TEST selects the calculation routine (newiculedrv vs otroiculedrv) and VERBOSE enables verbose output.'
    write (lu,'(a)') '- THREADS only takes effect if the binary was compiled with OpenMP.'
    write (lu,'(a)') ''
    write (lu,'(a)') '----------------------------------------------------------------------------------------------------------------'
    write (lu,'(a)') '4. NOTES'
    write (lu,'(a)') '----------------------------------------------------------------------------------------------------------------'
    write (lu,'(a)') ''
    write (lu,'(a)') '- Keywords are case-insensitive (the program uppercases the line before comparing).'
    write (lu,'(a)') '- THREADS arguments are read with Fortran list-directed input, so blanks or tabs may appear between the keyword and the value.'
    write (lu,'(a)') '- Any unrecognized keyword is silently ignored. If the first non-blank line does not contain a file name, the program aborts with:'
    write (lu,'(a)') ''
    write (lu,'(a)') '      ''# intracule.f: Fatal error. WFN file name not read in'''
    write (lu,'(a)') ''
    write (lu,'(a)') '- The WFN file must be in the working directory or given as an absolute or relative path.'
    write (lu,'(a)') ''
    write (lu,'(a)') '================================================================================================================'

    return
end subroutine usage
