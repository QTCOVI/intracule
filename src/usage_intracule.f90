!-----------------------------------------------------------------------
subroutine usage_intracule (u)
!
!-----Prints the documentation of all keywords that can appear
!     between INTRACULE and END in the input file.
!     Argument:
!       u : logical unit number where the text is written.
!           If u <= 0, unit 6 (stdout) is used.
!
    implicit none
    integer, intent(in) :: u
    integer :: lu

    lu = u
    if (lu <= 0) lu = 6

    write (lu,'(a)') '========================================================================================================='
    write (lu,'(a)') '        INTRACULE - KEYWORDS BETWEEN THE "INTRACULE" AND "END"'
    write (lu,'(a)') '========================================================================================================='
    write (lu,'(a)') ''
    write (lu,'(a)') 'The following keywords may appear in the input file between the INTRACULE and END keywords. They control'
    write (lu,'(a)') 'the calculation performed by the routine "otroiculedrv".'
    write (lu,'(a)') ''
    write (lu,'(a)') '--------------------------------------------------------------------------------------------------------'
    write (lu,'(a)') '1. OUTPUT CONTROL'
    write (lu,'(a)') '--------------------------------------------------------------------------------------------------------'
    write (lu,'(a)') ''
    write (lu,'(a)') 'VERBOSE'
    write (lu,'(a)') '    Usage:    VERBOSE'
    write (lu,'(a)') '    Effect:   Enables verbose output (verb=.true.). It may change the value of the input parameter verb.'
    write (lu,'(a)') '    Default:  verb = .false.'
    write (lu,'(a)') ''
    write (lu,'(a)') '--------------------------------------------------------------------------------------------------------'
    write (lu,'(a)') '2. RADIAL INTEGRATION'
    write (lu,'(a)') '--------------------------------------------------------------------------------------------------------'
    write (lu,'(a)') ''
    write (lu,'(a)') 'INTEGRATE [ ANALYTIC | NUMERICAL ]'
    write (lu,'(a)') '    Usage:    INTEGRATE [ ANALYTIC | NUMERICAL ]'
    write (lu,'(a)') '    Effect:   Requests the computation of the radial intracule density either analytically'
    write (lu,'(a)') '              (ANALYTIC) or numerically (NUMERICAL).'
    write (lu,'(a)') '    Default:  ANALYTIC'
    write (lu,'(a)') ''
    write (lu,'(a)') 'BESSEL'
    write (lu,'(a)') '    Usage:    BESSEL'
    write (lu,'(a)') '    Effect:   Requests the Bessel-like angular integration mode when computing the spherically averaged (or radial) intracule density.'
    write (lu,'(a)') '    Default:  .TRUE.'
    write (lu,'(a)') ''
    write (lu,'(a)') 'NOBESSEL'
    write (lu,'(a)') '    Usage:    NOBESSEL'
    write (lu,'(a)') '    Effect:   Disables the Bessel-like angular integration mode.'
    write (lu,'(a)') ''
    write (lu,'(a)') 'QUADPACK'
    write (lu,'(a)') '    Usage:    QUADPACK'
    write (lu,'(a)') '    Effect:   Uses QUADPACK (DQAGI routine) for the radial integration of the intracule density.'
    write (lu,'(a)') '    Default:  .FALSE.'
    write (lu,'(a)') ''
    write (lu,'(a)') 'NOQUADPACK'
    write (lu,'(a)') '    Usage:    NOQUADPACK'
    write (lu,'(a)') '    Effect:   Disables QUADPACK radial integration.'
    write (lu,'(a)') '    Default:  .TRUE. (QUADPACK disabled)'
    write (lu,'(a)') ''
    write (lu,'(a)') 'RMESH rmesh'
    write (lu,'(a)') '    Usage:    RMESH rmesh'
    write (lu,'(a)') '    Type:     integer (1, 2, or 3)'
    write (lu,'(a)') '    Effect:   Defines the radial quadrature and  r-mapping used in the radial integration.'
    write (lu,'(a)') '              rmesh = 1 : Becke radial grid r = rmid*(1+q)/(1-q), q uniform on (-1,+1)'
    write (lu,'(a)') '              rmesh = 2 : Euler-Maclaurin grid, n=1,  r = rmid*q/(1-q), q uniform on (0,+1)'
    write (lu,'(a)') '              rmesh = 3 : Euler-Maclaurin grid, n=2,  r = rmid*q^2/(1-q)^2, q uniform on (0,+1)'
    write (lu,'(a)') '    Default:  rmesh = 2'
    write (lu,'(a)') ''
    write (lu,'(a)') 'NRAD'
    write (lu,'(a)') '    Usage:    NRAD n'
    write (lu,'(a)') '    Type:     integer (2 <= n <= 1000)'
    write (lu,'(a)') '    Effect:   Number of r-points in radial integrations.'
    write (lu,'(a)') '    Default:  nrad = 101'
    write (lu,'(a)') ''
    write (lu,'(a)') 'RMID'
    write (lu,'(a)') '    Usage:    RMID rmid'
    write (lu,'(a)') '    Type:     real (0.05 <= rmid <= 10.0)'
    write (lu,'(a)') '    Effect:   Value of the rmid parameter in the r-mappings (see RMESH).'
    write (lu,'(a)') '    Default:  rmid = 0.5'
    write (lu,'(a)') ''
    write (lu,'(a)') 'RADIALGRID file_with_r_values [ ANALYTIC | NUMERICAL ]'
    write (lu,'(a)') '    Usage:    RADIALGRID file [ ANALYTIC | NUMERICAL ]'
    write (lu,'(a)') '    Effect:   Computes the radial intracule density at  the r points listed in file (one r value per line). ANALYTIC/NUMERICAL have the same meaning as in INTEGRATE.'
    write (lu,'(a)') '    Default:  not active'
    write (lu,'(a)') ''
    write (lu,'(a)') 'ABSQUADERR epsabs'
    write (lu,'(a)') '    Usage:    ABSQUADERR epsabs'
    write (lu,'(a)') '    Type:     real'
    write (lu,'(a)') '    Effect:   Absolute error requested in the QUADPACK integration of the intracule density.'
    write (lu,'(a)') '    Default:  epsabs = 1.0D-5'
    write (lu,'(a)') ''
    write (lu,'(a)') 'RELQUADERR epsrel'
    write (lu,'(a)') '    Usage:    RELQUADERR epsrel'
    write (lu,'(a)') '    Type:     real'
    write (lu,'(a)') '    Effect:   Relative error requested in the QUADPACK integration of the intracule density.'
    write (lu,'(a)') '    Default:  epsrel = 1.0D-5'
    write (lu,'(a)') ''
    write (lu,'(a)') '--------------------------------------------------------------------------------------------------------'
    write (lu,'(a)') '3. ANGULAR INTEGRATION'
    write (lu,'(a)') '--------------------------------------------------------------------------------------------------------'
    write (lu,'(a)') ''
    write (lu,'(a)') 'LEBEDEV [ nangular ]'
    write (lu,'(a)') '    Usage:    LEBEDEV [ nangular ]'
    write (lu,'(a)') '    Type:     integer (6 <= nangular <= 20000)'
    write (lu,'(a)') '    Effect:   Selects the Lebedev angular grid with nangular points for the numerical angular integration of the intracule density.'
    write (lu,'(a)') '    Default:  lebedev = .TRUE., nangular = 600'
    write (lu,'(a)') ''
    write (lu,'(a)') 'TDESIGN [ nangular ]'
    write (lu,'(a)') '    Usage:    TDESIGN [ nangular ]'
    write (lu,'(a)') '    Type:     integer (6 <= nangular <= 20000)'
    write (lu,'(a)') '    Effect:   Selects the spherical T-design grid with nangular points for the numerical angular integration of the intracule density.'
    write (lu,'(a)') '    Default:  tdesign = .FALSE.'
    write (lu,'(a)') ''
    write (lu,'(a)') 'GAUSS_JACOBI_POINTS nptsgj'
    write (lu,'(a)') '    Usage:    GAUSS_JACOBI_POINTS nptsgj'
    write (lu,'(a)') '    Type:     integer'
    write (lu,'(a)') '    Effect:   Number of points in the Gauss-Jacobi angular integration used in some variants of the radial intracule density computation.'
    write (lu,'(a)') '    Default:  nptsgj = 40'
    write (lu,'(a)') ''
    write (lu,'(a)') '--------------------------------------------------------------------------------------------------------'
    write (lu,'(a)') '4. GRID-BASED COMPUTATIONS'
    write (lu,'(a)') '--------------------------------------------------------------------------------------------------------'
    write (lu,'(a)') ''
    write (lu,'(a)') 'CUBIC [ MEM | DISK ] [ ngrid [ rmax ] ]'
    write (lu,'(a)') '    Usage:    CUBIC [ MEM | DISK ] [ ngrid [ rmax ] ]'
    write (lu,'(a)') '    Effect:   Computes the intracule density on a cubic grid with ngrid points per direction in the range -rmax <= x,y,z <= rmax.'
    write (lu,'(a)') '              MEM  : compute in memory (icule0grid, icule2grid for DERIV 2)'
    write (lu,'(a)') '              DISK : compute on disk (intraditp). If neither MEM nor DISK is given, DISK is used.'
    write (lu,'(a)') '    Default:  ngrid = 81, rmax = 10.0, disk = .TRUE.'
    write (lu,'(a)') ''
    write (lu,'(a)') 'CUBICGRID ...'
    write (lu,'(a)') 'NOGENGRID ...'
    write (lu,'(a)') '    Usage:    same as CUBIC'
    write (lu,'(a)') '    Effect:   Equivalent to CUBIC.'
    write (lu,'(a)') ''
    write (lu,'(a)') 'MEMORY'
    write (lu,'(a)') 'NODISK'
    write (lu,'(a)') '    Usage:    MEMORY  |  NODISK'
    write (lu,'(a)') '    Effect:   Sets MEM = .TRUE. and DISK = .FALSE.'
    write (lu,'(a)') '              (compute in memory).'
    write (lu,'(a)') ''
    write (lu,'(a)') 'DISK'
    write (lu,'(a)') 'NOMEMORY'
    write (lu,'(a)') '    Usage:    DISK  |  NOMEMORY'
    write (lu,'(a)') '    Effect:   Sets MEM = .FALSE. and DISK = .TRUE.'
    write (lu,'(a)') '              (compute on disk).'
    write (lu,'(a)') ''
    write (lu,'(a)') 'GENGRID file_with_xyz_values'
    write (lu,'(a)') 'FILEGRID file_with_xyz_values'
    write (lu,'(a)') 'NOCUBIC file_with_xyz_values'
    write (lu,'(a)') '    Usage:    GENGRID file  (or FILEGRID / NOCUBIC)'
    write (lu,'(a)') '    Effect:   Computes the intracule density at the (x,y,z) points listed in file. The amount of information depends on DERIV:'
    write (lu,'(a)') '              DERIV 0 : density only  (iculegen0)'
    write (lu,'(a)') '              DERIV 1 : density + gradient (iculegen1)'
    write (lu,'(a)') '              DERIV 2 : density + gradient + Laplacian (iculegen2)'
    write (lu,'(a)') '    Default:  not active'
    write (lu,'(a)') ''
    write (lu,'(a)') '--------------------------------------------------------------------------------------------------------'
    write (lu,'(a)') '5. DERIVATIVES'
    write (lu,'(a)') '--------------------------------------------------------------------------------------------------------'
    write (lu,'(a)') ''
    write (lu,'(a)') 'DERIV { deriv }'
    write (lu,'(a)') '    Usage:    DERIV deriv'
    write (lu,'(a)') '    Type:     integer (0, 1, or 2)'
    write (lu,'(a)') '    Effect:   Selects the amount of information computed at each point:'
    write (lu,'(a)') '              deriv = 0 : density only, deriv = 1 : density and gradient,  deriv = 2 : density, gradient and Laplacian'
    write (lu,'(a)') '              Values outside {0,1,2} are reset to 0.'
    write (lu,'(a)') '    Default:  deriv = 0'
    write (lu,'(a)') ''
    write (lu,'(a)') 'DMFTXC'
    write (lu,'(a)') '    Usage:    DMFTXC'
    write (lu,'(a)') '    Effect:   Uses a second order DMFTXC pair density in the Müller approximation'
    write (lu,'(a)') ''
    write (lu,'(a)') '--------------------------------------------------------------------------------------------------------'
    write (lu,'(a)') '6. END OF THE BLOCK'
    write (lu,'(a)') '--------------------------------------------------------------------------------------------------------'
    write (lu,'(a)') ''
    write (lu,'(a)') 'END'
    write (lu,'(a)') '    Usage:    END'
    write (lu,'(a)') '    Effect:   Closes the INTRACULE ... END block and returns control to intracule.f.'
    write (lu,'(a)') ''
    write (lu,'(a)') '========================================================================================================='

    return
end subroutine usage_intracule
